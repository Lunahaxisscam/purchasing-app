const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, '../public/upah-totalan-history.js');
assert.ok(fs.existsSync(file), 'display-only history adapter must exist');
const UI = require(file);
const t = { totalUpah: 86699600, openingAdjustment: -181750, kasbonDipotong: 103625000, hakBersih: -17107150, pembayaranAktual: 15000000, saldoAkhir: 0, final: true, carriedResidual: -32107150, residualBeforeCarry: -32107150, status: 'Lunas' };
const before = JSON.stringify(t);
const v = UI.summary(t);
assert.equal(v.opening, -181750);
assert.equal(v.ending, -32107150);
assert.equal(v.net, -17107150, 'opening already included in snapshot: do not add twice');
assert.equal(v.status, 'Selesai / Ditutup');
assert.equal(v.carried, true);
assert.equal(JSON.stringify(t), before, 'display must never mutate financial state');
console.log('PASS signed carry display, snapshot preserved, no mutation');
for (const opening of [-100, 0, 100]) {
  const row = {totalUpah:1000, kasbonDipotong:200, openingAdjustment:opening, hakBersih:800+opening, pembayaranAktual:800+opening, saldoAkhir:0, status:'Lunas'};
  assert.equal(UI.summary(row).net, 800+opening);
  assert.equal(UI.summary(row).ending, 0);
  assert.equal(UI.summary(row).carried, false);
  assert.equal(UI.summary(row).status, 'Lunas');
}
assert.equal(UI.summary({...t, residualBeforeCarry:null}).ending, -32107150);
assert.equal(UI.summary({...t, residualBeforeCarry:undefined}).ending, -32107150);
assert.equal(UI.summary({...t, residualBeforeCarry:0}).ending, 0, 'explicit zero is valid');
assert.equal(UI.summary({...t, carriedResidual:0, saldoAkhir:-12}).carried, false);
assert.equal(UI.summary({...t, carriedResidual:0, saldoAkhir:-12}).ending, -12);
assert.equal(UI.summary({...t, carriedResidual:100, residualBeforeCarry:100}).ending, 100);
assert.equal(UI.summary({...t, carriedResidual:100, residualBeforeCarry:100}).status, 'Selesai / Ditutup');
assert.equal(typeof UI.render, 'function', 'history must render two-column document, not old dense table');
const html = UI.render({...t,id:'x',no:'TOT-004',projectIds:['p'],potonganDetail:Array.from({length:50},(_,i)=>({tanggal:'2026-01-01',deskripsi:'Panjang <script>'+i,nominal:100}))}, {name:'PUJON',projects:[{id:'p',name:'Project <unsafe>'}],upahItems:[],projectOverrides:{p:86699600}}, {money:String,date:String,projectTotal:()=>86699600});
assert.match(html, /Upah \/ Pekerjaan/);
assert.match(html, /Kasbon dipotong/);
assert.match(html, /Saldo awal/);
assert.match(html, /Saldo akhir/);
assert.match(html, /Dibawa ke totalan berikutnya/);
assert.match(html, /Pembayaran aktual/);
assert.match(html, /Selesai \/ Ditutup/);
assert.match(html, /Project &lt;unsafe&gt;/);
assert.doesNotMatch(html, /<script>/);
assert.equal((html.match(/Panjang &lt;script&gt;/g)||[]).length, 50, 'all kasbon rows retained');
const chronology=UI.render({...t,potonganDetail:[{tanggal:'2026-02-01',deskripsi:'LATER'},{tanggal:'2025-01-01',deskripsi:'EARLIER'}]}, {projects:[]}, {money:String,date:String,projectTotal:()=>0});
assert.ok(chronology.indexOf('EARLIER')<chronology.indexOf('LATER'),'kasbon sorted by date for readability');
console.log('PASS positive/negative/zero, null carry fallback, explicit zero, two-column render, 50 kasbon and escaping');

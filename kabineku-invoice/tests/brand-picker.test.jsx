import {it,expect,vi} from 'vitest';
import React from 'react';
import {act as legacyAct} from 'react-dom/test-utils';
import {createRoot} from 'react-dom/client';
import {JSDOM} from 'jsdom';
const act=React.act||legacyAct;
const calls=vi.hoisted(()=>({crm:vi.fn(()=>({select:()=>({order:async()=>({data:[]})})})),list:vi.fn(),issue:vi.fn()}));
vi.mock('../../lib/supabaseClient',()=>({supabase:{from:calls.crm}}));
vi.mock('../../components/CompactRoot',()=>({default:({children})=><div>{children}</div>}));
vi.mock('../../modules/sales-invoice/pdf',()=>({buildSalesInvoicePdf:vi.fn(),downloadPdf:vi.fn(),missingPaymentFields:()=>[],missingIssuerFields:()=>[]}));
vi.mock('../../modules/sales-invoice/official',()=>({buildOfficialInvoicePdf:vi.fn(),downloadBytes:vi.fn()}));
vi.mock('../../modules/sales-invoice/apiClient',()=>({getAccessToken:async()=>null,listInvoices:calls.list,issueInvoice:calls.issue,markPaid:vi.fn(),markSent:vi.fn(),voidInvoice:vi.fn()}));
import Module from '../../modules/sales-invoice/view.jsx';
it('requires a brand choice; Kabineku never receives CRM and stays isolated; Noir path remains',async()=>{
 const dom=new JSDOM('<div id="app"></div>',{url:'http://localhost'});global.window=dom.window;global.document=dom.window.document;global.IS_REACT_ACT_ENVIRONMENT=true;
 const root=createRoot(document.querySelector('#app'));
 await act(async()=>root.render(<Module invoices={[]}/>));
 const click=async(text)=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.includes(text));expect(b).toBeTruthy();await act(async()=>b.click());};
 await click('+ Buat');
 expect(Boolean(document.querySelector('iframe'))).toBe(false);
 const picker=document.querySelector('[role="dialog"]');expect(picker).toBeTruthy();expect(picker.textContent).toContain('Kabineku');
 await click('Kabineku');
 let frame=document.querySelector('iframe');expect(frame.getAttribute('src')).toBe('/kabineku-invoice/index.html');expect(frame.getAttribute('sandbox')).not.toContain('allow-same-origin');
 const update=vi.fn();Object.defineProperty(frame,'contentWindow',{value:{__noirCrmUpdate:update}});
 const count=calls.crm.mock.calls.length;
 await act(async()=>frame.dispatchEvent(new window.Event('load')));
 expect(update).not.toHaveBeenCalled();expect(calls.crm).toHaveBeenCalledTimes(count);expect(calls.issue).not.toHaveBeenCalled();expect(calls.list).not.toHaveBeenCalled();
 await click('Kembali');await click('+ Buat');await click('Noir');
 frame=document.querySelector('iframe');expect(frame.getAttribute('src')).toBe('/noir-invoice/index.html');expect(frame.getAttribute('sandbox')).toContain('allow-same-origin');
 await act(async()=>root.unmount());dom.window.close();
});